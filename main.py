def download_page():

    request = Request(
        URL,
        headers={
            "User-Agent": (
                "Mozilla/5.0 "
                "(Windows NT 6.1; WOW64) "
                "AppleWebKit/537.36 "
                "Chrome/109.0 Safari/537.36"
            ),
            "Accept-Language": (
                "ru-RU,ru;q=0.9,en;q=0.8"
            )
        }
    )

    context = ssl._create_unverified_context()

    response = urlopen(
        request,
        timeout=90,
        context=context
    )

    data = response.read()

    encoding = "utf-8"

    content_type = response.headers.get(
        "Content-Type",
        ""
    )

    match = re.search(
        r"charset=([^\s;]+)",
        content_type,
        re.I
    )

    if match:
        encoding = match.group(1).strip("\"'")

    try:
        return data.decode(
            encoding,
            errors="replace"
        )

    except Exception:
        return data.decode(
            "utf-8",
            errors="replace"
        )


