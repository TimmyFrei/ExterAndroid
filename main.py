    def go_to_person_page(self, value, pages):
        try:
            target = int(value) - 1
        except (TypeError, ValueError):
            return

        self.change_page(
            max(
                0,
                min(target, pages - 1)
            )
        )

    def change_person_page_size(self, value):
        try:
            size = int(value)
        except (TypeError, ValueError):
            return

        if size == self.app.page_size:
            return

        self.app.page_size = size
        self.app.person_page = 0
        self.refresh()

