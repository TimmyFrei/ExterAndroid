        chart_holder=BoxLayout(orientation="vertical",size_hint_x=None)
        chart_scroll.add_widget(chart_holder)
        content.add_widget(chart_scroll)

        def rebuild(*_):
            chart_holder.clear_widgets()
            zoom_value.text=f"{zoom.value:.1f}×"
            mode=order.text
            sorted_items=(sorted(items,key=lambda x:int(x[0])) if mode=="По хронологии"
                          else sorted(items,key=lambda x:(-x[1],int(x[0]))))
            if not sorted_items:
                chart_holder.size_hint_x=1
                chart_holder.add_widget(Label(text="Нет данных"))
                return

            # При 1.0x диаграмма ровно такая же по ширине, как сейчас.
            # При увеличении каждая колонка получает больше места, а ScrollView
            # даёт возможность рассмотреть все годы на маленьком экране.
            viewport=max(chart_scroll.width,dp(300))
            chart_width=max(viewport*zoom.value,viewport)
            chart_holder.size_hint_x=None
            chart_holder.width=chart_width

            chart=BoxLayout(orientation="horizontal",spacing=dp(2),padding=(dp(4),dp(4)),
                            size_hint_x=None,width=chart_width)
            maxn=max(v for _,v in sorted_items) or 1
            col_width=max(dp(1), (chart_width-dp(8)-dp(2)*(len(sorted_items)-1))/float(len(sorted_items)))
            for year,count in sorted_items:
                pct=(count*100.0/total) if total else 0
                col=BoxLayout(orientation="vertical",spacing=dp(1),size_hint_x=None,width=col_width)
                info=RotatedYearLabel(year,count,pct,size_hint_y=None,height=dp(82))
                col.add_widget(info)
                plot=BoxLayout(orientation="vertical",spacing=0)
                ratio=count/float(maxn)
                if ratio < 0.025:
                    ratio=0.025
                spacer=Widget(size_hint_y=1-ratio)
                bar=YearBar(year,count,pct,self.show_year_detail,size_hint_y=ratio)
                plot.add_widget(spacer)
                plot.add_widget(bar)
                col.add_widget(plot)
                chart.add_widget(col)
            chart_holder.add_widget(chart)

