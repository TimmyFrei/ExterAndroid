        def on_zoom(instance, value):
            # Масштаб меняет только ширину области диаграммы. Сам экран и
            # ScrollView при этом не пересоздаются, поэтому перетаскивание
            # ползунка не превращается в горизонтальную прокрутку.
            zoom_value.text=f"{value:.1f}×"
            if sorted_items_cache:
                update_chart_width(value)

        # Кэш последних данных диаграммы нужен, чтобы при изменении масштаба
        # не пересобирать все столбцы заново.
        sorted_items_cache=[]

        def update_chart_width(scale):
            viewport=max(chart_scroll.width,dp(300))
            chart_width=max(viewport*scale,viewport)
            chart_holder.width=chart_width
            if chart_holder.children:
                chart=chart_holder.children[0]
                chart.width=chart_width
                col_width=max(dp(1), (chart_width-dp(8)-dp(2)*(len(sorted_items_cache)-1))/float(len(sorted_items_cache)))
                for col in reversed(chart.children):
                    col.width=col_width
                    for child in col.children:
                        if isinstance(child, RotatedYearLabel):
                            continue
                # Перестраиваем только ширину колонок, не трогая ScrollView.
                for col in chart.children:
                    col.width=col_width

        # Перехватываем rebuild через небольшой wrapper, чтобы сохранить
        # список годов для изменения ширины при движении ползунка.
        original_rebuild=rebuild
        def rebuild_with_cache(*args):
            original_rebuild(*args)
            mode=order.text
            sorted_items_cache[:] = (sorted(items,key=lambda x:int(x[0])) if mode=="По хронологии"
                                     else sorted(items,key=lambda x:(-x[1],int(x[0]))))

        zoom.bind(value=on_zoom)
        order.unbind(text=rebuild)
        order.bind(text=rebuild_with_cache)
        # Первый расчёт после layout, чтобы chart_scroll.width уже был
        # реальной шириной области на экране. При 1.0x все столбцы
        # обязаны уместиться именно в эту ширину.
        from kivy.clock import Clock
        Clock.schedule_once(lambda *_: rebuild_with_cache(), 0)

        close=Button(text="Закрыть",size_hint_y=None,height=dp(42))
        content.add_widget(close)
        popup=Popup(title=f"Год рождения  •  {self.mode.text}",content=content,size_hint=(.99,.96),auto_dismiss=False)
        close.bind(on_release=popup.dismiss)
        popup.open()

