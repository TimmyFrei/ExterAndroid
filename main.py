    def group_count(self,rows,key,numeric=False,sort_mode="count"):
        d={}
        for r in rows:
            k=key(r)
            if k in (None,"", "None"): continue
            d[str(k)]=d.get(str(k),0)+1
        items=list(d.items())
        if sort_mode=="chronology":
            if numeric:
                return sorted(items,key=lambda x:int(x[0]))
            return sorted(items,key=lambda x:x[0].casefold())
        if sort_mode=="alphabet":
            return sorted(items,key=lambda x:x[0].casefold())
        return sorted(items,key=lambda x:(-x[1],x[0].casefold()))

