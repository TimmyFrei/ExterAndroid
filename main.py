def parse_date(value):

    if not value:
        return None

    match = re.search(
        r"(\d{2})\.(\d{2})\.(\d{4})",
        str(value)
    )

    if not match:
        return None

    try:

        return date(
            int(match.group(3)),
            int(match.group(2)),
            int(match.group(1))
        )

    except ValueError:
        return None


def calculate_age(birth_date):

    if birth_date is None:
        return None

    today = date.today()

    age = (
        today.year
        - birth_date.year
        - (
            (today.month, today.day)
            <
            (birth_date.month, birth_date.day)
        )
    )

    return age


