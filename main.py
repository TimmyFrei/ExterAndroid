class MobileDatabase:
    """SQLite-хранилище мобильной версии.

    Схема совместима с последней десктопной версией Экстера.
    """

    def __init__(self, path):
        self.con = sqlite3.connect(str(path), check_same_thread=False)
        self.con.execute("PRAGMA foreign_keys = ON")
        self.prepare()

    def prepare(self):
        with self.con:
            self.con.execute("""
                CREATE TABLE IF NOT EXISTS persons (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    fio TEXT NOT NULL,
                    birth_date TEXT,
                    birth_year INTEGER,
                    birth_place TEXT,
                    terrorism_charge INTEGER NOT NULL DEFAULT 0,
                    raw_text TEXT,
                    imported_at TEXT
                )
            """)
            self.con.execute("""
                CREATE TABLE IF NOT EXISTS organizations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    details TEXT,
                    terrorism_charge INTEGER NOT NULL DEFAULT 0,
                    raw_text TEXT,
                    imported_at TEXT
                )
            """)
            self.con.execute("""
                CREATE TABLE IF NOT EXISTS region_aliases (
                    alias TEXT PRIMARY KEY,
                    region TEXT NOT NULL
                )
            """)
            self.con.execute("CREATE INDEX IF NOT EXISTS idx_persons_fio ON persons(fio)")
            self.con.execute("CREATE INDEX IF NOT EXISTS idx_persons_birth_year ON persons(birth_year)")
            self.con.execute("CREATE INDEX IF NOT EXISTS idx_persons_terrorism ON persons(terrorism_charge)")
            self.con.execute("CREATE INDEX IF NOT EXISTS idx_organizations_name ON organizations(name)")
            self.con.execute("CREATE INDEX IF NOT EXISTS idx_organizations_terrorism ON organizations(terrorism_charge)")

    def load_persons(self):
        rows = self.con.execute("""
            SELECT fio,birth_date,birth_year,birth_place,terrorism_charge,raw_text
            FROM persons ORDER BY fio COLLATE NOCASE
        """).fetchall()
        result = []
        for fio, bd, by, bp, tc, raw in rows:
            result.append({
                "fio": fio or "", "birth_date": bd or "", "birth_year": by,
                "birth_place": bp or "", "terrorism_charge": int(tc or 0),
                "raw_text": raw or "", "birth_date_obj": parse_date(bd)
            })
        return result

    def load_organizations(self):
        rows = self.con.execute("""
            SELECT name,details,terrorism_charge,raw_text
            FROM organizations ORDER BY name COLLATE NOCASE
        """).fetchall()
        return [{
            "name": n or "", "details": d or "", "terrorism_charge": int(tc or 0),
            "raw_text": raw or ""
        } for n,d,tc,raw in rows]

    def load_aliases(self):
        return dict(self.con.execute("SELECT alias,region FROM region_aliases").fetchall())

    def replace_all(self, persons, organizations):
        now = datetime.now().isoformat(" ", "seconds")
        with self.con:
            self.con.execute("DELETE FROM persons")
            self.con.execute("DELETE FROM organizations")
            self.con.executemany("""
                INSERT INTO persons(fio,birth_date,birth_year,birth_place,terrorism_charge,raw_text,imported_at)
                VALUES(?,?,?,?,?,?,?)
            """, [(r["fio"],r.get("birth_date",""),r.get("birth_year"),r.get("birth_place",""),
                    r.get("terrorism_charge",0),r.get("raw_text",""),now) for r in persons])
            self.con.executemany("""
                INSERT INTO organizations(name,details,terrorism_charge,raw_text,imported_at)
                VALUES(?,?,?,?,?)
            """, [(r["name"],r.get("details",""),r.get("terrorism_charge",0),r.get("raw_text",""),now)
                   for r in organizations])

    def save_alias(self, alias, region):
        with self.con:
            self.con.execute("INSERT OR REPLACE INTO region_aliases(alias,region) VALUES(?,?)", (alias,region))

    def clear(self):
        with self.con:
            self.con.execute("DELETE FROM persons")
            self.con.execute("DELETE FROM organizations")

    def close(self):
        self.con.close()


